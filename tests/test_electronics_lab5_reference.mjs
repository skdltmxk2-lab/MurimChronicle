const cache = new Map();
function load(name) {
  if (cache.has(name)) return cache.get(name);
  const module = { exports: {} };
  const source = ts.transpileModule(readFileSync(new URL(`../src/lib/electronics/${name}.ts`, import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  new Function("module", "exports", "require", source)(module, module.exports, dependency => load(dependency.slice(2)));
  cache.set(name, module.exports); return module.exports;
}
const { buildLab5ReferenceCircuit, buildLab5ReferenceCase, LAB5_REFERENCE_CASES, lab5Measurements, lab5TonePeak } = load("lab5-reference");
const { runSimulation } = load("simulation"), { COMPONENT_CATALOG } = load("catalog");
const { createLayout, validateLayout } = load("engine");
const near = (actual, expected, tolerance) => assert.ok(Math.abs(actual - expected) <= tolerance, `${actual} != ${expected}, tol ${tolerance}`);
const run = (id, ratio = "1:1") => { const { circuit, config } = buildLab5ReferenceCase(id, ratio); return runSimulation(circuit, COMPONENT_CATALOG, config); };

test("three source topologies preserve separate base dividers, CT node, BC109C terminals and RF coupling", () => {
  for (const number of [1, 2, 3]) {
    const circuit = buildLab5ReferenceCircuit(number, "1:1"), byId = Object.fromEntries(circuit.components.map(part => [part.id, part]));
    assert.equal(byId.Q1.definitionId, "bjt-bc109c-philips-to18"); assert.deepEqual(byId.Q1.pinNets, { 1: "TAIL", 2: "B1", 3: "OUT1" });
    assert.deepEqual(byId.Q3.pinNets, { 1: "E3", 2: "B3", 3: "TAIL" });
    assert.equal(Boolean(byId.RB11), number < 3); assert.equal(Boolean(byId.RB21), number === 1); assert.equal(Boolean(byId.CIN), number !== 2);
    if (number > 1) {
      assert.deepEqual(byId.T1.pinNets, { 1: "LO", 2: "GND", 3: "B2", 4: "CT", 5: "B1" });
      assert.deepEqual(byId.RBCT1.pinNets, { 1: "VCC", 2: "CT" }); assert.deepEqual(byId.RBCT2.pinNets, { 1: "CT", 2: "GND" });
    }
    assert.match(circuit.notes.join(" "), /빵판 배치.*검증/);
    assert.ok(circuit.reviewItems.some(item => !item.resolved));
  }
  assert.throws(() => buildLab5ReferenceCircuit(4, "1:1")); assert.throws(() => buildLab5ReferenceCircuit(2, "CS195")); assert.throws(() => buildLab5ReferenceCase("arbitrary-user-netlist", "1:1"));
});

