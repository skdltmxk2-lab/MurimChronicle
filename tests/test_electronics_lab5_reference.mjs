const textIn = node => Array.isArray(node) ? node.map(textIn).join("") : node?.props ? textIn(node.props.children) : typeof node === "string" || typeof node === "number" ? String(node) : "";
function* walk(node) { if (Array.isArray(node)) { for (const child of node) yield* walk(child); return; } if (!node?.props) return; yield node; yield* walk(node.props.children); }
function uiHarness(initialUser = { id: "admin-1", admin: true }) {
  const slots = [], effects = [], workers = [], timers = new Map(), downloads = [];
  let user = initialUser, cursor = 0, dirty = true, tree, timerId = 0;
  const same = (a, b) => a && b && a.length === b.length && a.every((value, i) => Object.is(value, b[i]));
  const react = {
    useState(initial) { const index = cursor++; slots[index] ??= { value: typeof initial === "function" ? initial() : initial }; const slot = slots[index]; slot.set ??= value => { const next = typeof value === "function" ? value(slot.value) : value; if (!Object.is(next, slot.value)) { slot.value = next; dirty = true; } }; return [slot.value, slot.set]; },
    useRef(initial) { const index = cursor++; return slots[index] ??= { current: initial }; },
    useMemo(factory, deps) { const index = cursor++, previous = slots[index]; if (!previous || !same(previous.deps, deps)) slots[index] = { value: factory(), deps }; return slots[index].value; },
    useCallback(fn, deps) { return react.useMemo(() => fn, deps); },
    useEffect(effect, deps) { const index = cursor++, previous = slots[index]; if (!previous || !same(previous.deps, deps)) { const slot = { deps, cleanup: previous?.cleanup }; slots[index] = slot; effects.push(() => { slot.cleanup?.(); slot.cleanup = effect(); }); } },
  };
  class WorkerMock { constructor() { workers.push(this); this.terminated = false; } postMessage(message) { this.request = message; } terminate() { this.terminated = true; } emit(message) { this.onmessage?.({ data: message }); } }
  const module = { exports: {} }, jsx = (type, props, key) => ({ type, props: props ?? {}, key });
  const code = ts.transpileModule(readFileSync(new URL("../src/components/electronics/Lab5ReferencePanel.tsx", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX } }).outputText.replaceAll("import.meta.url", JSON.stringify(import.meta.url));
  new Function("module", "exports", "require", "Worker", "URL", "setTimeout", "clearTimeout", code)(module, module.exports, name => {
    if (name === "react") return react;
    if (name === "react/jsx-runtime") return { jsx, jsxs: jsx, Fragment: "fragment" };
    if (name === "next/link") return { default: "a" };
    if (name === "next/image") return { default: "img" };
    if (name === "@/lib/auth/AuthContext") return { useAuth: () => ({ user, authChecked: true }) };
    if (name === "@/lib/auth/mockAuth") return { isAdminUser: value => Boolean(value?.admin) };
    if (name === "@/lib/electronics/storage") return { downloadText: (...args) => downloads.push(args) };
    if (name.startsWith("@/lib/electronics/")) return load(name.split("/").at(-1));
    if (name === "./Oscilloscope") return { Oscilloscope: "scope" };
    if (name.endsWith(".css")) return {};
    throw Error(`Unexpected module ${name}`);
  }, WorkerMock, URL, (fn, delay) => { timers.set(++timerId, { fn, delay }); return timerId; }, id => timers.delete(id));
  const flush = () => { for (let count = 0; dirty || effects.length; count++) { assert.ok(count < 20); if (dirty) { dirty = false; cursor = 0; tree = module.exports.Lab5ReferencePanel(); } for (const effect of effects.splice(0)) effect(); } return tree; };
  const find = predicate => { const node = [...walk(tree)].find(predicate); assert.ok(node); return node; };
  flush();
  return { workers, timers, downloads, get tree() { return tree; }, flush,
    click(label) { find(node => node.type === "button" && textIn(node).includes(label)).props.onClick(); flush(); },
    changeCase(value) { find(node => node.type === "select" && LAB5_REFERENCE_CASES.some(item => item.id === node.props.value)).props.onChange({ target: { value } }); flush(); },
    changeUser(next) { user = next; dirty = true; flush(); },
    unmount() { slots.forEach(slot => slot.cleanup?.()); },
  };
}

test("reference UI denies non-admin entry and cancels a running calculation on role revocation", () => {
  const denied = uiHarness(null); assert.match(textIn(denied.tree), /관리자 전용/); assert.equal([...walk(denied.tree)].filter(node => node.type === "select").length, 0);
  const h = uiHarness(); h.click("이 조건으로 계산"); const worker = h.workers.at(-1);
  h.changeUser({ id: "admin-1", admin: false }); assert.equal(worker.terminated, true); assert.equal(h.timers.size, 0); assert.match(textIn(h.tree), /관리자 전용/);
  worker.emit({ type: "error", requestId: worker.request.requestId, message: "stale forbidden" }); h.flush(); assert.doesNotMatch(textIn(h.tree), /stale forbidden/);
});

test("case changes, cancellation, timeout and unmount reject late worker replies", () => {
  const h = uiHarness(); h.click("이 조건으로 계산"); const first = h.workers.at(-1); h.changeCase("c2-drive");
  assert.equal(first.terminated, true); first.emit({ type: "error", requestId: first.request.requestId, message: "old case error" }); h.flush(); assert.doesNotMatch(textIn(h.tree), /old case error/);
  h.click("이 조건으로 계산"); const second = h.workers.at(-1); h.click("계산 중단"); assert.equal(second.terminated, true); assert.equal(h.timers.size, 0);
  h.click("이 조건으로 계산"); const third = h.workers.at(-1); const timer = [...h.timers.values()][0]; assert.equal(timer.delay, 20000); timer.fn(); h.flush(); assert.equal(third.terminated, true); assert.match(textIn(h.tree), /20초/);
  third.emit({ type: "error", requestId: third.request.requestId, message: "late timeout error" }); h.flush(); assert.doesNotMatch(textIn(h.tree), /late timeout error/);
  h.click("이 조건으로 계산"); const fourth = h.workers.at(-1); h.unmount(); assert.equal(fourth.terminated, true); assert.equal(h.timers.size, 0);
});

