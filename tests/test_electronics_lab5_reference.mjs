test("tone projection returns peak, not RMS or twice the reported sine amplitude", () => {
  const time = Array.from({ length: 2561 }, (_, i) => i * .005 / 2560);
  const values = time.map(t => .9 * Math.sin(2 * Math.PI * 10000 * t) + .15 * Math.sin(2 * Math.PI * 9000 * t) + .15 * Math.sin(2 * Math.PI * 11000 * t));
  near(lab5TonePeak(time, values, 10000), .9, 1e-10); near(lab5TonePeak(time, values, 9000), .15, 1e-10); near(lab5TonePeak(time, values, 11000), .15, 1e-10);
  assert.throws(() => lab5TonePeak([], [], 10000));
});

