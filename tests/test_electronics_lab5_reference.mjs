test("actual DC and transient engine agree with independent ngspice47 reduced-model netlists", () => {
  // Reference generated by scripts/reference/lab5_ngspice.py from an independently
  // transcribed circuit, 300 K, Ebers–Moll IS/BF/BR, same ideal ratio and windows.
  // These are solver-equivalence checks, NOT claims of matching the full PDF model.
  for (const id of ["c1-dc", "c1-drive", "c2-dc", "c2-drive"]) {
    const result = run(id);
    near(result.dc.nodeVoltages.OUT1, 6.5291209249, 5e-6);
    near(result.dc.nodeVoltages.B3, 1.1412838709, 5e-6);
    assert.ok(Object.values(result.nodeVoltages).every(values => values.every(Number.isFinite)));
    if (id === "c1-drive") { const metrics = lab5Measurements(result, id); assert.deepEqual(metrics.measurementWindow, [.0045, .0055]); near(metrics.halfVpp.OUT1, 1.904461052, .001905); }
    if (id === "c2-drive") { const metrics = lab5Measurements(result, id); assert.deepEqual(metrics.measurementWindow, [.0003, .0005]); near(metrics.halfVpp.OUT1, .472007068, .000473); near(metrics.halfVpp.B1, .00249994, .000003); }
  }
  const mixing = run("c3-mix"), metrics = lab5Measurements(mixing, "c3-mix");
  assert.deepEqual(metrics.measurementWindow, [.003, .005]);
  near(metrics.tonePeak["9000"], .182259554, .000183); near(metrics.tonePeak["10000"], .958651114, .000959); near(metrics.tonePeak["11000"], .182225981, .000183);
});

